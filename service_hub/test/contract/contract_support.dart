/// Where `python tools/export_contract.py --copy-to ...` puts the backend contract.
const contractFilePath = 'test/contract/data/contract.json';

/// "/api/v1/services/{service_id}" -> "/api/v1/services/{}"
String normalizePath(String path) => path.replaceAll(RegExp(r'\{[^}]*\}'), '{}');

String _normalizeKey(String key) {
  final space = key.indexOf(' ');
  return '${key.substring(0, space)} ${normalizePath(key.substring(space + 1))}';
}

typedef FoundOperation = ({String template, Map<String, dynamic> operation});

/// The backend's API contract: FastAPI's OpenAPI document plus example responses
/// generated from its schemas (see backend `tools/export_contract.py`).
class ApiContract {
  ApiContract._(this.spec, this.samples);

  final Map<String, dynamic> spec;

  /// "METHOD /normalized/path" -> {"full": ..., "nulls": ...}
  final Map<String, Map<String, dynamic>> samples;

  static ApiContract load() {
    final file = File(contractFilePath);
    if (!file.existsSync()) {
      throw TestFailure(
        'Missing $contractFilePath - the contract is generated by the backend:\n'
        '  cd backend_updated\n'
        '  python tools/export_contract.py --copy-to "<this project>/$contractFilePath"',
      );
    }
    final data = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
    final raw = data['samples'] as Map<String, dynamic>;
    return ApiContract._(
      data['openapi'] as Map<String, dynamic>,
      {
        for (final e in raw.entries)
          _normalizeKey(e.key): (e.value as Map).cast<String, dynamic>(),
      },
    );
  }

  Map<String, dynamic> get paths => (spec['paths'] as Map).cast<String, dynamic>();

  Map<String, dynamic> get schemas =>
      (((spec['components'] as Map?)?['schemas']) as Map?)?.cast<String, dynamic>() ?? {};

  /// An operation by *template* path, e.g. ("GET", "/api/v1/services/{}").
  Map<String, dynamic>? operationFor(String method, String templatePath) {
    for (final entry in paths.entries) {
      if (normalizePath(entry.key) != templatePath) continue;
      final op = (entry.value as Map)[method.toLowerCase()];
      return op == null ? null : (op as Map).cast<String, dynamic>();
    }
    return null;
  }

  /// An operation by *concrete* path, e.g. ("GET", "/api/v1/services/100").
  /// When several templates match, the one with fewer {params} wins, so
  /// "/appointments/me" beats "/appointments/{id}".
  FoundOperation? operationForRequest(String method, String concretePath) {
    FoundOperation? best;
    var bestParams = 1 << 30;
    for (final entry in paths.entries) {
      final op = (entry.value as Map)[method.toLowerCase()];
      if (op == null) continue;
      final pattern = RegExp(
        '^${entry.key.split('/').map((s) => s.startsWith('{') ? '[^/]+' : RegExp.escape(s)).join('/')}\$',
      );
      if (!pattern.hasMatch(concretePath)) continue;
      final params = '{'.allMatches(entry.key).length;
      if (params < bestParams) {
        bestParams = params;
        best = (template: entry.key, operation: (op as Map).cast<String, dynamic>());
      }
    }
    return best;
  }

  Map<String, dynamic> resolve(Map<String, dynamic> schema) {
    var current = schema;
    while (current[r'$ref'] is String) {
      final name = (current[r'$ref'] as String).split('/').last;
      final next = schemas[name];
      if (next == null) throw StateError('Unknown schema reference: $name');
      current = (next as Map).cast<String, dynamic>();
    }
    return current;
  }

  Map<String, dynamic>? requestBodySchema(Map<String, dynamic> operation) {
    final body = operation['requestBody'] as Map<String, dynamic>?;
    final content = body?['content'] as Map<String, dynamic>?;
    final json = content?['application/json'] as Map<String, dynamic>?;
    return json?['schema'] as Map<String, dynamic>?;
  }

  bool requestBodyRequired(Map<String, dynamic> operation) =>
      (operation['requestBody'] as Map?)?['required'] == true;

  List<Map<String, dynamic>> queryParameters(Map<String, dynamic> operation) => [
        for (final p in (operation['parameters'] as List?) ?? const [])
          if ((p as Map)['in'] == 'query') p.cast<String, dynamic>(),
      ];
}

// ============================================================ schema validation

String _kind(dynamic v) => v == null ? 'null' : v.runtimeType.toString();

/// A small JSON-schema checker (enough for what FastAPI emits). Returns the
/// problems found; an empty list means [value] is valid.
List<String> validateSchema(
  ApiContract contract,
  dynamic value,
  Map<String, dynamic> schema,
  String path,
) {
  final s = contract.resolve(schema);

  if (s['allOf'] is List) {
    return [
      for (final part in s['allOf'] as List)
        ...validateSchema(contract, value, (part as Map).cast<String, dynamic>(), path),
    ];
  }
  for (final key in const ['anyOf', 'oneOf']) {
    final alternatives = s[key];
    if (alternatives is List) {
      final results = [
        for (final alt in alternatives)
          validateSchema(contract, value, (alt as Map).cast<String, dynamic>(), path),
      ];
      if (results.any((r) => r.isEmpty)) return const <String>[];
      results.sort((a, b) => a.length.compareTo(b.length));
      return results.first; // the alternative that came closest
    }
  }

  if (s['enum'] is List && !(s['enum'] as List).contains(value)) {
    return ['$path: "$value" is not one of ${s['enum']}'];
  }
  if (s.containsKey('const') && s['const'] != value) {
    return ['$path: expected ${s['const']}, got "$value"'];
  }

  final errors = <String>[];
  switch (s['type']) {
    case 'null':
      if (value != null) errors.add('$path: expected null, got ${_kind(value)}');
    case 'object':
      if (value is! Map) {
        errors.add('$path: expected an object, got ${_kind(value)}');
        break;
      }
      final props = ((s['properties'] as Map?) ?? const {}).cast<String, dynamic>();
      final required = ((s['required'] as List?) ?? const []).cast<String>();
      for (final name in required) {
        if (!value.containsKey(name)) {
          errors.add('$path.$name: required by the backend but not sent');
        }
      }
      final freeForm = props.isEmpty && s['additionalProperties'] != null;
      for (final entry in value.entries) {
        final name = '${entry.key}';
        final propSchema = props[name];
        if (propSchema == null) {
          if (!freeForm) {
            errors.add('$path.$name: the backend has no such field (it would be ignored)');
          }
          continue;
        }
        errors.addAll(validateSchema(
          contract, entry.value, (propSchema as Map).cast<String, dynamic>(), '$path.$name',
        ));
      }
    case 'array':
      if (value is! List) {
        errors.add('$path: expected a list, got ${_kind(value)}');
        break;
      }
      final items = s['items'];
      if (items is Map) {
        for (var i = 0; i < value.length; i++) {
          errors.addAll(validateSchema(contract, value[i], items.cast<String, dynamic>(), '$path[$i]'));
        }
      }
    case 'string':
      if (value is! String) {
        errors.add('$path: expected a string, got ${_kind(value)}');
        break;
      }
      final min = s['minLength'];
      final max = s['maxLength'];
      if (min is int && value.length < min) errors.add('$path: shorter than $min characters');
      if (max is int && value.length > max) errors.add('$path: longer than $max characters');
      if (s['format'] == 'date-time' && DateTime.tryParse(value) == null) {
        errors.add('$path: "$value" is not an ISO date-time');
      }
    case 'integer':
      final isInt = value is int || (value is double && value == value.truncateToDouble());
      if (!isInt) {
        errors.add('$path: expected an integer, got ${_kind(value)} ($value)');
        break;
      }
      errors.addAll(_numberLimits(s, value as num, path));
    case 'number':
      if (value is! num) {
        errors.add('$path: expected a number, got ${_kind(value)}');
        break;
      }
      errors.addAll(_numberLimits(s, value, path));
    case 'boolean':
      if (value is! bool) errors.add('$path: expected true/false, got ${_kind(value)}');
  }
  return errors;
}

List<String> _numberLimits(Map<String, dynamic> s, num value, String path) {
  final errors = <String>[];
  if (s['minimum'] is num && value < (s['minimum'] as num)) {
    errors.add('$path: $value is below the minimum ${s['minimum']}');
  }
  if (s['maximum'] is num && value > (s['maximum'] as num)) {
    errors.add('$path: $value is above the maximum ${s['maximum']}');
  }
  if (s['exclusiveMinimum'] is num && value <= (s['exclusiveMinimum'] as num)) {
    errors.add('$path: $value must be greater than ${s['exclusiveMinimum']}');
  }
  if (s['exclusiveMaximum'] is num && value >= (s['exclusiveMaximum'] as num)) {
    errors.add('$path: $value must be less than ${s['exclusiveMaximum']}');
  }
  return errors;
}

/// Query strings are text: turn "10.0" / "true" back into what the backend parses.
Object coerceQueryValue(String raw) {
  if (raw == 'true') return true;
  if (raw == 'false') return false;
  return int.tryParse(raw) ?? double.tryParse(raw) ?? raw;
}

// ================================================================ read recording

class ReadLog {
  /// Every key a model asked for, e.g. "profile.full_name".
  final Set<String> read = {};

  /// The keys it asked for that the response did not contain.
  final Set<String> missing = {};
}

/// A map that remembers which keys `fromJson` reads. Nested maps and lists are
/// wrapped too, so reads deep inside the response are recorded as well.
class RecordingMap extends MapBase<String, dynamic> {
  RecordingMap(this._inner, this._path, this._log);

  final Map<String, dynamic> _inner;
  final String _path;
  final ReadLog _log;

  @override
  dynamic operator [](Object? key) {
    final name = '$key';
    final fullPath = _path.isEmpty ? name : '$_path.$name';
    _log.read.add(fullPath);
    if (!_inner.containsKey(name)) {
      _log.missing.add(fullPath);
      return null;
    }
    return wrapRecording(_inner[name], fullPath, _log);
  }

  @override
  void operator []=(String key, dynamic value) => _inner[key] = value;

  @override
  void clear() => _inner.clear();

  @override
  Iterable<String> get keys => _inner.keys;

  @override
  dynamic remove(Object? key) => _inner.remove(key);
}

dynamic wrapRecording(dynamic value, String path, ReadLog log) {
  if (value is Map<String, dynamic>) return RecordingMap(value, path, log);
  if (value is List) return [for (final e in value) wrapRecording(e, '$path[]', log)];
  return value;
}
